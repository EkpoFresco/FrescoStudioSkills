#!/usr/bin/env node
// Regenerates studio-tests/catalog.yaml from studio/skills and studio/agents, keeping any
// last_* results already recorded. `--check` exits 1 if an item lacks a category or spec file
// (this is what /skill-test audit counts as passing).
'use strict';
const fs = require('fs');
const path = require('path');
const REPO = path.resolve(__dirname, '..');
const CAT = path.join(REPO, 'studio-tests', 'catalog.yaml');

const SKILL_CAT = {
  setup: ['rbx-start', 'rbx-toolchain', 'rbx-checkpoint', 'rbx-resume'],
  design: ['rbx-concept', 'rbx-genre', 'rbx-first-60', 'rbx-loop', 'rbx-plan', 'rbx-monetize', 'rbx-thumbnail'],
  build: ['rbx-build', 'rbx-art', 'rbx-telemetry'],
  audit: ['rbx-remote-audit', 'rbx-data-audit', 'rbx-perf', 'rbx-review', 'rbx-optimize', 'rbx-playtest'],
  growth: ['rbx-teardown', 'rbx-metrics', 'rbx-launch', 'rbx-update'],
  team: ['rbx-issues', 'rbx-handoff', 'rbx-pickup', 'rbx-ship'],
};
const AGENT_CAT = {
  director: ['roblox-director'],
  designer: ['discovery-strategist', 'retention-designer', 'genre-designer', 'monetization-designer', 'ux-mobile-designer', 'liveops-designer', 'community-marketer'],
  engineer: ['luau-architect', 'server-programmer', 'client-ui-programmer', 'data-engineer', 'analytics-engineer', 'art-generator'],
  quality: ['code-optimizer', 'exploit-tester', 'qa-playtester'],
  coordination: ['team-coordinator'],
};
const PRIORITY = { 'code-optimizer': 'critical', 'rbx-build': 'critical', 'rbx-review': 'critical', 'rbx-data-audit': 'critical', 'rbx-remote-audit': 'critical', 'rbx-ship': 'critical', 'rbx-start': 'high', 'rbx-resume': 'high', 'rbx-checkpoint': 'high', 'rbx-playtest': 'high', 'rbx-optimize': 'high' };
const inv = (m) => Object.fromEntries(Object.entries(m).flatMap(([c, ns]) => ns.map((n) => [n, c])));
const sc = inv(SKILL_CAT), ac = inv(AGENT_CAT);

// keep previous results
const prev = {};
if (fs.existsSync(CAT)) {
  let cur = null;
  for (const l of fs.readFileSync(CAT, 'utf8').split(/\r?\n/)) {
    const n = l.match(/^\s*- name:\s*(\S+)/); if (n) { cur = n[1]; prev[cur] = {}; continue; }
    const k = l.match(/^\s+(last_\w+):\s*"?([^"]*)"?\s*$/); if (cur && k) prev[cur][k[1]] = k[2];
  }
}
const skills = fs.readdirSync(path.join(REPO, 'studio', 'skills')).filter((d) => fs.existsSync(path.join(REPO, 'studio', 'skills', d, 'SKILL.md'))).sort();
const agents = fs.readdirSync(path.join(REPO, 'studio', 'agents')).filter((f) => f.endsWith('.md')).map((f) => f.slice(0, -3)).sort();
const problems = [];
const fields = ['last_static', 'last_static_result', 'last_spec', 'last_spec_result', 'last_category', 'last_category_result'];
let out = `# Generated by tools/gen-catalog.js. Edit categories there; results are kept on regenerate.\nversion: 3\nskills:\n`;
for (const n of skills) {
  const c = sc[n]; if (!c) problems.push(`skill ${n}: no category`);
  const spec = `studio-tests/skills/${c}/${n}.md`;
  if (!fs.existsSync(path.join(REPO, spec))) problems.push(`skill ${n}: missing spec ${spec}`);
  out += `  - name: ${n}\n    spec: ${spec}\n    category: ${c}\n    priority: ${PRIORITY[n] || 'medium'}\n`;
  for (const f of fields) out += `    ${f}: "${(prev[n] || {})[f] || ''}"\n`;
}
out += 'agents:\n';
for (const n of agents) {
  const c = ac[n]; if (!c) problems.push(`agent ${n}: no category`);
  const spec = `studio-tests/agents/${c}/${n}.md`;
  if (!fs.existsSync(path.join(REPO, spec))) problems.push(`agent ${n}: missing spec ${spec}`);
  out += `  - name: ${n}\n    spec: ${spec}\n    category: ${c}\n    priority: ${PRIORITY[n] || 'medium'}\n`;
  for (const f of fields.filter((x) => !x.startsWith('last_static'))) out += `    ${f}: "${(prev[n] || {})[f] || ''}"\n`;
}
for (const c of Object.values(SKILL_CAT).flat()) if (!skills.includes(c)) problems.push(`catalogued skill ${c} has no file`);
for (const c of Object.values(AGENT_CAT).flat()) if (!agents.includes(c)) problems.push(`catalogued agent ${c} has no file`);
if (!process.argv.includes('--check')) fs.writeFileSync(CAT, out);
console.log(`skills ${skills.length}, agents ${agents.length}, problems ${problems.length}`);
problems.forEach((p) => console.log('  ' + p));
process.exit(problems.length && process.argv.includes('--check') ? 1 : 0);
